const fn ctrl_named(key: NamedKey) -> KeyPress {
    KeyPress {
        control: true,
        ..KeyPress::named(key)
    }
}

const fn ctrl_shift_named(key: NamedKey) -> KeyPress {
    KeyPress {
        control: true,
        shift: true,
        ..KeyPress::named(key)
    }
}

const fn shift_named(key: NamedKey) -> KeyPress {
    KeyPress {
        shift: true,
        ..KeyPress::named(key)
    }
}

const fn ctrl_alt(character: char) -> KeyPress {
    KeyPress {
        alt: true,
        ..KeyPress::ctrl(character)
    }
}

